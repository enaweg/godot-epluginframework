#if TOOLS
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security;

namespace Enaweg.Plugin.Internal.Dotnet;

/// <summary>
/// A build of the Godot project without the project's own code: only compile items and project references below
/// <paramref name="PluginRoots"/> (<c>addons/</c>, recipe projects elsewhere) stay. It tells whether the plugins
/// compile on their own when the full build failed. Its outputs go to <paramref name="WorkDirectory"/>, never to the
/// folder the editor loads the assembly from, which its clean would empty.
/// </summary>
/// <param name="WorkDirectory">An empty folder for the targets file and the outputs; the caller deletes it.</param>
/// <param name="PluginRoots">Absolute directories whose code counts as plugin code.</param>
/// <param name="ErrorLog">Where MSBuild writes the build's errors, one per line.</param>
internal sealed record PluginsOnlyBuild(string WorkDirectory, IReadOnlyList<string> PluginRoots, string ErrorLog)
{
    public string TargetsFile => Path.Combine(WorkDirectory, "plugins-only.targets");
    // Without a trailing separator: quoted for the command line, a path ending in a backslash would escape its closing
    // quote on Windows. MSBuild adds the separator OutDir needs.
    public string OutputDirectory => Path.Combine(WorkDirectory, "bin");

    /// <summary>
    /// Imported after Microsoft.Common.targets into every project of the build (global properties reach referenced
    /// projects), so it acts only on the Godot project. It filters in a target rather than at evaluation, where item
    /// metadata cannot be used in conditions. A Rebuild resolves project references while cleaning, before BeforeBuild,
    /// and targets run once, so it runs before whichever of these comes first.
    /// </summary>
    public static string Targets(string godotProject, IReadOnlyList<string> pluginRoots)
    {
        if (pluginRoots.Count == 0) throw new System.ArgumentException("A plugins-only build needs at least the addons directory.", nameof(pluginRoots));
        var outside = string.Join(" and ", pluginRoots.Select(root =>
            $"!$([System.String]::Copy('%(FullPath)').StartsWith('{Literal(Directory(root))}', StringComparison.OrdinalIgnoreCase))"));
        return $"""
            <Project>
              <!-- Generated by ePlugin for a plugins-only build; see PluginsOnlyBuild. -->
              <Target Name="EPluginPluginsOnly" BeforeTargets="BeforeRebuild;BeforeBuild;AssignProjectConfiguration" Condition="'$(MSBuildProjectFullPath)' == '{Literal(Path.GetFullPath(godotProject))}'">
                <ItemGroup>
                  <Compile Remove="@(Compile)" Condition="{outside}" />
                  <ProjectReference Remove="@(ProjectReference)" Condition="{outside}" />
                </ItemGroup>
              </Target>
            </Project>
            """;
    }

    /// <summary>The arguments after <c>dotnet</c>, one per element.</summary>
    public string[] Arguments(string godotProject) =>
    [
        "build", godotProject, "-c", "Debug", "--no-incremental",
        "-p:CustomAfterMicrosoftCommonTargets=" + Escape(TargetsFile), "-p:OutDir=" + Escape(OutputDirectory),
        "-fileLoggerParameters:LogFile=" + ErrorLog + ";ErrorsOnly;Encoding=UTF-8",
    ];

    public void WriteTargets(string godotProject)
    {
        System.IO.Directory.CreateDirectory(WorkDirectory);
        File.WriteAllText(TargetsFile, Targets(godotProject, PluginRoots));
    }

    private static string Directory(string path) => Path.TrimEndingDirectorySeparator(Path.GetFullPath(path)) + Path.DirectorySeparatorChar;

    /// <summary>A path inside a quoted MSBuild string in an XML attribute.</summary>
    private static string Literal(string value) => SecurityElement.Escape(Escape(value))!;

    /// <summary>
    /// MSBuild's special characters escaped, for the targets file and for property values on the command line: MSBuild
    /// expands a property inside item transforms, which an apostrophe in the path would end.
    /// </summary>
    private static string Escape(string value) =>
        value.Replace("%", "%25").Replace("$", "%24").Replace("@", "%40").Replace("'", "%27").Replace(";", "%3B").Replace("*", "%2A").Replace("?", "%3F");
}
#endif
